//! WebAssembly owns the immutable card catalogue and every mutable position.
//! JavaScript exchanges JSON only at explicit API boundaries; proof-tree state
//! copies, action generation, transitions, hashing and transpositions stay here.

use omni_rs::{
    search::{Limits, Search},
    Engine, Seat, State,
};
use serde::Deserialize;
use serde_json::{json, Value};
use std::{rc::Rc, time::Duration};
use wasm_bindgen::prelude::*;

fn error(message: impl AsRef<str>) -> JsError {
    JsError::new(message.as_ref())
}

#[derive(Deserialize)]
#[serde(default, deny_unknown_fields, rename_all = "camelCase")]
struct ProofLimits {
    depth: u16,
    nodes: Option<u64>,
    ms: Option<f64>,
    table_entries: usize,
}

impl Default for ProofLimits {
    fn default() -> Self {
        let limits = Limits::default();
        Self {
            depth: limits.depth,
            nodes: None,
            ms: None,
            table_entries: limits.table_entries,
        }
    }
}

fn parse_limits(text: &str) -> Result<Limits, String> {
    let raw: ProofLimits =
        serde_json::from_str(text).map_err(|e| format!("invalid proof limits: {e}"))?;
    let time = raw
        .ms
        .map(|ms| {
            Duration::try_from_secs_f64(ms / 1000.)
                .map_err(|_| format!("invalid millisecond budget {ms}"))
        })
        .transpose()?;
    Ok(Limits {
        depth: raw.depth,
        nodes: raw.nodes,
        time,
        table_entries: raw.table_entries,
    })
}

/// Loaded once and shared by any number of independent game handles.
#[wasm_bindgen]
pub struct WasmEngine {
    engine: Rc<Engine>,
}

#[wasm_bindgen]
impl WasmEngine {
    /// `pool_json` is the exact UTF-8 pool file, not a reserialized object.
    /// Its SHA-256 must match reference traces and exported positions.
    #[wasm_bindgen(constructor)]
    pub fn new(pool_json: &str) -> Result<WasmEngine, JsError> {
        let engine = Engine::from_pool_bytes(pool_json.as_bytes()).map_err(error)?;
        Ok(Self {
            engine: Rc::new(engine),
        })
    }

    #[wasm_bindgen(js_name = poolHash)]
    pub fn pool_hash(&self) -> String {
        self.engine.pool_hash().to_string()
    }

    /// Imports an independently complete action-window snapshot. Use clone()
    /// to checkpoint a position with unresolved prompts.
    #[wasm_bindgen(js_name = loadState)]
    pub fn load_state(&self, state_json: &str) -> Result<WasmGame, JsError> {
        let value: Value = serde_json::from_str(state_json)
            .map_err(|e| error(format!("invalid state JSON: {e}")))?;
        let state = self.engine.load_state(&value).map_err(error)?;
        omni_rs::check::compare_states(&value, &self.engine.snapshot(&state)).map_err(error)?;
        Ok(WasmGame {
            engine: Rc::clone(&self.engine),
            state,
        })
    }
}

/// A mutable position retained inside Wasm. Explicit free() is generated by
/// wasm-bindgen; clones retain their catalogue after the engine handle is freed.
#[wasm_bindgen]
pub struct WasmGame {
    engine: Rc<Engine>,
    state: State,
}

#[wasm_bindgen]
impl WasmGame {
    #[wasm_bindgen(js_name = clone)]
    pub fn clone_game(&self) -> WasmGame {
        Self {
            engine: Rc::clone(&self.engine),
            state: self.state,
        }
    }

    pub fn snapshot(&self) -> String {
        self.engine.snapshot(&self.state).to_string()
    }

    /// Each action object includes its canonical JSON tuple in `key`.
    /// `actor` optionally chooses a seat while regroup choices are simultaneous;
    /// enumeration does not change the position.
    #[wasm_bindgen(js_name = legalActions)]
    pub fn legal_actions(&self, actor: Option<String>) -> Result<String, JsError> {
        let state = self.for_actor(actor)?;
        let actions: Vec<Value> = self
            .engine
            .legal_actions(&state)
            .into_iter()
            .map(|action| {
                let key = action.key();
                let mut value =
                    serde_json::to_value(action).expect("action serialization cannot fail");
                value["key"] = json!(key);
                value
            })
            .collect();
        Ok(serde_json::to_string(&actions).expect("actions serialization cannot fail"))
    }

    /// Applies one explicit canonical action. Validation and execution happen on
    /// a copy, so an invalid actor or action cannot partially mutate the handle.
    pub fn apply(&mut self, action_key: &str, actor: Option<String>) -> Result<(), JsError> {
        let state = self.for_actor(actor)?;
        let parsed: Value = serde_json::from_str(action_key)
            .map_err(|e| error(format!("invalid action key JSON: {e}")))?;
        if parsed.as_array().is_none_or(|tuple| tuple.len() != 5) {
            return Err(error(
                "action key must be the five-element canonical JSON tuple",
            ));
        }
        let key = parsed.to_string();
        let action = self
            .engine
            .legal_actions(&state)
            .into_iter()
            .find(|a| a.key() == key)
            .ok_or_else(|| error(format!("illegal action: {key}")))?;
        let next = self.engine.apply(&state, &action).map_err(error)?;
        self.state = next;
        Ok(())
    }

    /// Selects a still-pending simultaneous regroup seat. Outside regroup the
    /// supplied seat must already be the current actor.
    #[wasm_bindgen(js_name = setActor)]
    pub fn set_actor(&mut self, actor: &str) -> Result<(), JsError> {
        let mut next = self.state;
        self.engine
            .set_actor(&mut next, Seat::parse(actor).map_err(error)?)
            .map_err(error)?;
        self.state = next;
        Ok(())
    }

    /// Runs the complete native AND/OR algorithm synchronously inside Wasm.
    /// The game handle is unchanged. Put this call in a Worker for browser UIs.
    pub fn prove(&self, limits_json: &str) -> Result<String, JsError> {
        let limits = parse_limits(limits_json).map_err(error)?;
        let result = Search::new(self.engine.as_ref())
            .solve(self.state, limits)
            .map_err(error)?;
        serde_json::to_string(&result).map_err(|e| error(e.to_string()))
    }

    /// Benchmarks complete action windows entirely inside Wasm, using exactly
    /// the native CLI's deterministic rollout and checksum. The handle is intact.
    /// A Number is validated before conversion, avoiding JS-to-u32 wraparound.
    pub fn bench(&self, nodes: f64) -> Result<String, JsError> {
        if !nodes.is_finite() || nodes < 1. || nodes.fract() != 0. || nodes > u32::MAX as f64 {
            return Err(error("bench nodes must be an integer in 1..=4294967295"));
        }
        if !self.state.is_action_window() {
            return Err(error("bench requires a nonterminal action-window position"));
        }
        let wanted = nodes as u64;
        let initial = self.state;
        let mut state = initial;
        let mut random = 0x6a09e667f3bcc909u64;
        let mut nodes = 0u64;
        let mut decisions = 0u64;
        let mut games = 0u64;
        let mut checksum = 0u64;
        let mut prompt_steps = 0usize;
        let start = web_time::Instant::now();
        loop {
            if state.is_terminal() {
                games += 1;
                checksum ^= state.zobrist();
                state = initial;
            }
            if state.is_action_window() {
                if nodes >= wanted {
                    break;
                }
                nodes += 1;
                prompt_steps = 0;
                checksum = checksum.rotate_left(1) ^ state.zobrist();
            } else {
                prompt_steps += 1;
                if prompt_steps > 100_000 {
                    return Err(error("benchmark stuck in prompts for 100000 inputs"));
                }
            }
            let actions = self.engine.legal_actions(&state);
            if actions.is_empty() {
                return Err(error(
                    "benchmark reached nonterminal state without legal actions",
                ));
            }
            random ^= random << 13;
            random ^= random >> 7;
            random ^= random << 17;
            // Reduce before narrowing: wasm32 usize must select the same move
            // as a 64-bit native build for an identical deterministic workload.
            state = self
                .engine
                .apply(&state, &actions[(random % actions.len() as u64) as usize])
                .map_err(error)?;
            decisions += 1;
        }
        let seconds = start.elapsed().as_secs_f64();
        Ok(json!({ "benchmark": "complete_action_windows", "runtime": "wasm", "source": "retained-state",
            "nodes": nodes, "decisions": decisions, "games": games, "seconds": seconds,
            "nodesPerSecond": nodes as f64 / seconds, "microsecondsPerNode": seconds * 1_000_000. / nodes as f64,
            "stateBytes": std::mem::size_of::<State>(), "threads": 1, "checksum": checksum,
            "checksumHex": format!("{checksum:016x}"), "setupExcluded": true,
            "profile": if cfg!(debug_assertions) { "debug" } else { "release" } }).to_string())
    }

    pub fn actor(&self) -> Option<String> {
        self.state.actor().map(|s| s.as_str().to_owned())
    }
    pub fn round(&self) -> u16 {
        self.state.round
    }
    #[wasm_bindgen(js_name = isActionWindow)]
    pub fn is_action_window(&self) -> bool {
        self.state.is_action_window()
    }
    pub fn over(&self) -> bool {
        self.state.is_terminal()
    }
    pub fn winner(&self) -> Option<String> {
        if self.state.outcome == 3 {
            Some("draw".into())
        } else {
            self.state.winner().map(|s| s.as_str().to_owned())
        }
    }
    pub fn phase(&self) -> String {
        if self.state.regroup {
            "regroup"
        } else {
            "action"
        }
        .into()
    }
    #[wasm_bindgen(js_name = poolHash)]
    pub fn pool_hash(&self) -> String {
        self.engine.pool_hash().to_string()
    }
    #[wasm_bindgen(js_name = stateHash)]
    pub fn state_hash(&self) -> String {
        format!("{:016x}", self.state.zobrist())
    }
}

impl WasmGame {
    fn for_actor(&self, actor: Option<String>) -> Result<State, JsError> {
        let mut state = self.state;
        if let Some(actor) = actor {
            let seat = Seat::parse(&actor).map_err(error)?;
            self.engine.set_actor(&mut state, seat).map_err(error)?;
        }
        Ok(state)
    }
}

#[wasm_bindgen]
pub fn capabilities() -> String {
    json!({ "schema": "omni-wasm-v1", "crateVersion": env!("CARGO_PKG_VERSION"),
        "persistentStates": true, "searchInWasm": true, "stateBytes": std::mem::size_of::<State>(),
        "actionKey": "[kind,card,arg,method,label]", "snapshotImport": "action-window",
        "simultaneousRegroup": "prover-first-defender-second" })
    .to_string()
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn limits_keep_native_semantics_and_reject_typos_and_invalid_numbers() {
        let limits = parse_limits(r#"{"depth":4,"nodes":23,"ms":0.5,"tableEntries":0}"#).unwrap();
        assert_eq!(
            (limits.depth, limits.nodes, limits.table_entries),
            (4, Some(23), 0)
        );
        assert_eq!(limits.time, Some(Duration::from_micros(500)));
        for input in [
            r#"{"node":23}"#,
            r#"{"depth":-1}"#,
            r#"{"depth":65536}"#,
            r#"{"ms":-0.5}"#,
            r#"{"nodes":1.5}"#,
        ] {
            assert!(parse_limits(input).is_err(), "{input} must be rejected");
        }
        assert_eq!(parse_limits("{}").unwrap().depth, Limits::default().depth);
    }
}
